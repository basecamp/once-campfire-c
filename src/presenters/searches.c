static cf_span searches_span(const char *text) {
    return (cf_span){(const unsigned char *)text, strlen(text)};
}

/* Strict UTF-8 decode; false on a malformed sequence. */
static bool searches_utf8_next(cf_span text, size_t *index, uint32_t *cp) {
    size_t i = *index;
    if (i >= text.len) return false;
    unsigned char b = text.ptr[i];
    size_t len;
    uint32_t value;
    if (b < 0x80) {
        len = 1;
        value = b;
    } else if ((b & 0xE0) == 0xC0) {
        len = 2;
        value = b & 0x1F;
    } else if ((b & 0xF0) == 0xE0) {
        len = 3;
        value = b & 0x0F;
    } else if ((b & 0xF8) == 0xF0) {
        len = 4;
        value = b & 0x07;
    } else {
        return false;
    }
    if (i + len > text.len) return false;
    for (size_t k = 1; k < len; k++) {
        unsigned char c = text.ptr[i + k];
        if ((c & 0xC0) != 0x80) return false;
        value = (value << 6) | (c & 0x3F);
    }
    /* Overlongs and out-of-range values are malformed, as Rust's String
     * invariant would make them unreachable. */
    if ((len == 2 && value < 0x80) || (len == 3 && value < 0x800) ||
        (len == 4 && value < 0x10000) || value > 0x10FFFF) {
        return false;
    }
    *index = i + len;
    *cp = value;
    return true;
}

/* `is_word`: Onigmo's `[[:word:]]` (alphabetic, marks, decimal digits,
 * connector punctuation and join controls), the pinned Unicode 15.0 table. */
static bool searches_is_word(uint32_t cp) {
    size_t lo = 0,
           hi = sizeof SEARCH_WORD_RANGES / sizeof SEARCH_WORD_RANGES[0];
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (cp < SEARCH_WORD_RANGES[mid].first) {
            hi = mid;
        } else if (cp > SEARCH_WORD_RANGES[mid].last) {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}

/* `char::is_whitespace` (Unicode White_Space), for `is_present`. */
static bool searches_is_whitespace(uint32_t cp) {
    return (cp >= 0x09 && cp <= 0x0D) || cp == 0x20 || cp == 0x85 ||
           cp == 0xA0 || cp == 0x1680 || (cp >= 0x2000 && cp <= 0x200A) ||
           cp == 0x2028 || cp == 0x2029 || cp == 0x202F || cp == 0x205F ||
           cp == 0x3000;
}

cf_err cf_searches_sanitize_query(cf_span q, cf_str *out) {
    if (out == NULL) return CF_INVALID;
    out->ptr = NULL;
    out->len = 0;
    if (q.len != 0 && q.ptr == NULL) return CF_INVALID;
    /* One space per replaced code point; a kept code point copies its own
     * bytes, so the input length is an upper bound and the result never
     * grows. */
    char *buffer = malloc(q.len + 1);
    if (buffer == NULL) return CF_NOMEM;
    size_t at = 0, i = 0;
    while (i < q.len) {
        size_t start = i;
        uint32_t cp = 0;
        if (!searches_utf8_next(q, &i, &cp)) {
            /* Ruby's gsub raises ArgumentError: invalid byte sequence. */
            free(buffer);
            return CF_INTERNAL;
        }
        if (searches_is_word(cp)) {
            memcpy(buffer + at, q.ptr + start, i - start);
            at += i - start;
        } else {
            buffer[at++] = ' ';
        }
    }
    buffer[at] = '\0';
    out->ptr = buffer;
    out->len = at;
    return CF_OK;
}

bool cf_searches_query_present(cf_span value) {
    if (value.len != 0 && value.ptr == NULL) return false;
    size_t i = 0;
    while (i < value.len) {
        uint32_t cp = 0;
        if (!searches_utf8_next(value, &i, &cp)) return true; /* not a space */
        if (!searches_is_whitespace(cp)) return true;
    }
    return false;
}

/* Owned copy of a span (the model's strings). */
static cf_err searches_str_copy(cf_span text, cf_str *out) {
    out->ptr = NULL;
    out->len = 0;
    if (text.len == 0) return CF_OK;
    char *copy = malloc(text.len + 1);
    if (copy == NULL) return CF_NOMEM;
    memcpy(copy, text.ptr, text.len);
    copy[text.len] = '\0';
    out->ptr = copy;
    out->len = text.len;
    return CF_OK;
}

static cf_err searches_str_vector_push(cf_view_str_vector *vector, cf_span text) {
    if (vector->len == vector->cap) {
        size_t cap = vector->cap == 0 ? 4 : vector->cap * 2;
        cf_str *items = realloc(vector->items, cap * sizeof *items);
        if (items == NULL) return CF_NOMEM;
        vector->items = items;
        vector->cap = cap;
    }
    cf_str copied = {0};
    cf_err rc = searches_str_copy(text, &copied);
    if (rc != CF_OK) return rc;
    vector->items[vector->len++] = copied;
    return CF_OK;
}

/* `concerns::last_room_visited_in`: the `last_room` cookie's room when the
 * user is a member of it, else the user's original room; `None` (0 here)
 * leaves the exit button at `/rooms/0`. */
static cf_err searches_last_room_visited(cf_ctx *ctx, int64_t user_id,
                                         int64_t *out_room_id) {
    *out_room_id = 0;
    cf_span cookie = {NULL, 0};
    cf_err rc = cf_ctx_cookie_get(ctx, searches_span("last_room"), &cookie);
    if (rc == CF_NOT_FOUND) rc = CF_OK;
    if (rc != CF_OK) return rc;
    int64_t requested = 0;
    if (cookie.len != 0 && cf_views_integer_cast(cookie, &requested)) {
        cf_room room = {0};
        bool found = false;
        rc = cf_room_find_for_user(ctx->reader, user_id, requested, &found,
                                   &room);
        cf_room_dispose(&room);
        if (rc != CF_OK) return rc;
        if (found) {
            *out_room_id = requested;
            return CF_OK;
        }
    }
    cf_room room = {0};
    bool found = false;
    rc = cf_room_original_for_user(ctx->reader, user_id, &found, &room);
    if (rc == CF_OK && found) *out_room_id = room.id;
    cf_room_dispose(&room);
    return rc;
}

cf_err cf_presenter_searches_index(cf_ctx *ctx, const cf_user *user, bool has_q,
                                   cf_span q,
                                   cf_view_searches_index_model *out) {
    if (ctx == NULL || user == NULL || out == NULL) return CF_INVALID;
    memset(out, 0, sizeof *out);

    cf_err rc = CF_OK;
    cf_message_vector messages = {0};
    cf_search_vector searches = {0};
    bool in_read = false;

    if (has_q) {
        if (q.len != 0 && q.ptr == NULL) return CF_INVALID;
        rc = searches_str_copy(q, &out->q);
        if (rc != CF_OK) goto fail;
        out->has_q = true;
        rc = cf_searches_sanitize_query(q, &out->query);
        if (rc != CF_OK) goto fail;
        out->has_query = true;
    }

    bool searchable =
        out->has_query && cf_searches_query_present((cf_span){
                             (const unsigned char *)out->query.ptr,
                             out->query.len});

    rc = cf_read_begin(ctx->reader);
    if (rc != CF_OK) goto fail;
    in_read = true;

    if (searchable) {
        rc = cf_message_search_reachable(ctx->reader, user->id, out->query,
                                         &messages);
    }
    if (rc == CF_OK) {
        rc = cf_search_ordered_for_user(ctx->reader, user->id, &searches);
    }
    for (size_t i = 0; rc == CF_OK && i < searches.len; i++) {
        cf_span text = {(const unsigned char *)searches.items[i].query.ptr,
                        searches.items[i].query.len};
        rc = searches_str_vector_push(&out->recent_searches, text);
    }
    if (rc == CF_OK) {
        rc = searches_last_room_visited(ctx, user->id, &out->return_to_room_id);
    }
    if (rc == CF_OK) {
        rc = cf_presenter_messages_in_transaction(ctx, messages.items,
                                                  messages.len, &out->messages);
    }

    cf_search_vector_dispose(&searches);
    cf_message_vector_dispose(&messages);
    {
        cf_err end_rc = cf_read_end(ctx->reader);
        in_read = false;
        if (rc == CF_OK) rc = end_rc;
    }
    if (rc != CF_OK) {
        cf_view_searches_index_model_dispose(out);
        return rc;
    }
    return CF_OK;

fail:
    if (in_read) {
        cf_err end_rc = cf_read_end(ctx->reader);
        (void)end_rc;
    }
    cf_search_vector_dispose(&searches);
    cf_message_vector_dispose(&messages);
    cf_view_searches_index_model_dispose(out);
    return rc;
}
